def dedupe(items: list[dict]) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    for item in items:
        slug = item["slug"]
        base = slug
        n = 2
        while slug in seen:
            slug = f"{base}-{n}"
            n += 1
        item = dict(item)
        item["slug"] = slug
        seen.add(slug)
        out.append(item)
    return out


